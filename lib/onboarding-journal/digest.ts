import "server-only"
import catalog from "./catalog.json"
import { REGISTER_STEP_ID, UNKNOWN } from "./labels"
import type {
  Journey,
  JourneyCoverage,
  OnboardingDataset,
  OnboardingEventDoc,
  OnboardingSessionDoc,
  PermissionKind,
  ScreenInfo,
  StepVisit,
} from "./types"

// Reduces the raw journal (one session record + its events) to one `Journey`
// per session: the per-screen figures and the few facts the Onboarding page
// aggregates. Event names and fields are the mobile app's
// (lotus-mobile/src/constants/analyticsEvents.ts, ONBOARDING_EVENTS).

interface CatalogStep {
  type: string
  title: string
  saveTo: string
  maxSelections?: number
  options?: { value: string; label: string }[]
}

// Generated by scripts/generate-onboarding-catalog.mjs.
const CATALOG = catalog.steps as Record<string, CatalogStep>
const GOAL_TITLES: Record<string, string> = catalog.goals

/** Fields whose free text names the person: their values are never listed. */
const PERSONAL_FIELDS = new Set(["preferredName", "firstName", "lastName"])

const PERMISSION_KIND_BY_STEP_TYPE: Record<string, PermissionKind> = {
  preNotification: "notifications",
  healthPermission: "health",
}

// On Android a system dialog (permission prompt, Health Connect, Google
// account picker) pauses the app, which the journal logs like a trip to the
// background. On the screens that open one, a background therefore says
// nothing there. iOS shows those dialogs without leaving the foreground.
const SYSTEM_DIALOG_STEP_TYPES = new Set(["preNotification", "healthPermission", "register"])

/** `detail` of a register_error that is no error: the form asking to confirm an address that looks mistyped. */
const EMAIL_TYPO_PROMPT = "email_typo_suggested"

/** A register_cancel and a register_error this close belong to one sign-in attempt (4 to 11 ms apart in practice). */
const SAME_ATTEMPT_MS = 1_000

// The documents come straight from phones: every field is read defensively.
const text = (value: unknown): string | undefined => (typeof value === "string" && value !== "" ? value : undefined)
const finite = (value: unknown): number | undefined =>
  typeof value === "number" && Number.isFinite(value) ? value : undefined

function screenInfo(stepId: string, loggedType: string | undefined): ScreenInfo {
  if (stepId === REGISTER_STEP_ID) return { title: "Création du compte", type: "register" }
  const known = CATALOG[stepId]
  if (!known) return { title: stepId, type: loggedType ?? UNKNOWN }
  return {
    title: known.title || stepId,
    type: known.type,
    field: known.saveTo,
    ...(known.maxSelections !== undefined ? { maxSelections: known.maxSelections } : {}),
    ...(known.options ? { options: Object.fromEntries(known.options.map((o) => [o.value, o.label])) } : {}),
    ...(PERSONAL_FIELDS.has(known.saveTo) ? { personal: true } : {}),
  }
}

// The session record holds the whole registration form, defaults included
// (age 0, bleedingOngoing false, an all-false medicalJourney…): only what was
// actually answered is kept.
function isBlank(value: unknown): boolean {
  if (value === null || value === undefined || value === "" || value === 0 || value === false) return true
  if (Array.isArray(value)) return value.every(isBlank)
  if (typeof value === "object") return Object.values(value as object).every(isBlank)
  return false
}

function cleanAnswers(raw: unknown): { name?: string; answers: Record<string, unknown> } {
  const answers: Record<string, unknown> = {}
  let name: string | undefined
  if (raw && typeof raw === "object" && !Array.isArray(raw)) {
    for (const [key, value] of Object.entries(raw as Record<string, unknown>)) {
      if (key === "preferredName") name = text(value)?.trim() || undefined
      else if (!isBlank(value)) answers[key] = value
    }
  }
  return { name, answers }
}

function parseConsentChoices(value: string | undefined): Record<string, boolean> | undefined {
  if (!value) return undefined
  try {
    const parsed: unknown = JSON.parse(value)
    if (!parsed || typeof parsed !== "object") return undefined
    const choices: Record<string, boolean> = {}
    for (const [key, checked] of Object.entries(parsed as Record<string, unknown>)) {
      if (typeof checked === "boolean") choices[key] = checked
    }
    return Object.keys(choices).length > 0 ? choices : undefined
  } catch {
    return undefined
  }
}

const push = <T>(list: T[] | undefined, item: T): T[] => (list ? [...list, item] : [item])
const pushOnce = (list: string[] | undefined, item: string): string[] | undefined =>
  list?.includes(item) ? list : push(list, item)
const bump = (count: number | undefined): number => (count ?? 0) + 1

function buildJourney(
  session: OnboardingSessionDoc,
  events: OnboardingEventDoc[],
  seeScreen: (stepId: string, loggedType: string | undefined) => void,
): Journey {
  const steps = new Map<string, StepVisit>()
  const stepTypes = new Map<string, string>()
  // Screens shown and not left yet → time already spent on them, known from
  // the last time the app went to the background.
  const openMs = new Map<string, number>()
  // Single-choice screens → options tapped: a second tap on the same option is no change of mind.
  const picked = new Map<string, Set<string>>()
  // Programme goals → last state of each box that was touched.
  const programGoals = new Map<string, boolean>()

  const journey: Journey = {
    id: session.id,
    flow: text(session.flow) ?? "onboarding",
    status: text(session.status) ?? "in_progress",
    platform: text(session.platform) ?? UNKNOWN,
    appVersion: text(session.appVersion) ?? UNKNOWN,
    lang: text(session.lang) ?? UNKNOWN,
    branch: text(session.branch),
    coverage: "partial",
    startedAt: finite(session.startedAt) ?? 0,
    lastActivityAt: Math.max(finite(session.updatedAt) ?? 0, finite(session.startedAt) ?? 0),
    completedAt: finite(session.completedAt),
    registeredAt: finite(session.registeredAt),
    paywallAt: finite(session.paywallAt),
    registerMethod: text(session.registerMethod),
    paywallResult: text(session.paywallResult),
    userId: text(session.userId),
    launches: 0,
    device: {
      width: finite(session.screenW),
      height: finite(session.screenH),
      fontScale: finite(session.fontScale),
      os: text(session.osVersion),
    },
    ...cleanAnswers(session.answers),
    steps: [],
    lastStepId: text(session.lastStepId),
  }

  const closeVisit = (stepId: string) => {
    const pending = openMs.get(stepId)
    const visit = steps.get(stepId)
    if (visit && pending) visit.ms += pending
    openMs.delete(stepId)
  }

  let firstView: OnboardingEventDoc | undefined
  // Last screen shown, and how long its last visit lasted when it was left.
  let lastVisit: { stepId: string; leftAfterMs?: number } | undefined
  // Last Apple or Google sheet logged as dismissed: a failed sign-in is logged the same way, then as an error.
  let lastCancel: { method: string | undefined; at: number } | undefined
  // The onboarding was finished at least once / when the account was first created.
  let finished = false
  let firstAccountAt: number | undefined

  /** First display of a screen in the journal. */
  const show = (stepId: string, event: OnboardingEventDoc): StepVisit => {
    const loggedType = text(event.stepType)
    if (loggedType) stepTypes.set(stepId, loggedType)
    seeScreen(stepId, loggedType)
    const shown: StepVisit = { id: stepId, index: finite(event.stepIndex), branch: text(event.branch), views: 1, ms: 0 }
    steps.set(stepId, shown)
    openMs.set(stepId, 0)
    lastVisit = { stepId }
    return shown
  }

  for (const event of events) {
    const name = text(event.name)
    const at = finite(event.t)
    if (at !== undefined && at > journey.lastActivityAt) journey.lastActivityAt = at
    const stepId = text(event.stepId)
    let visit = stepId ? steps.get(stepId) : undefined
    const value = text(event.value)
    const durationMs = finite(event.durationMs)

    // Something happened on a screen the journal never showed: its `step_view`
    // was lost on the way (events are sent in batches). The screen was on
    // display all the same.
    if (stepId && !visit && name !== "step_view" && name !== "session_start") visit = show(stepId, event)

    switch (name) {
      case "session_start":
        // The app reopened after the onboarding was finished (on the sign-up
        // screen, or an account sent back to the last screen): no pause in the
        // onboarding itself.
        if (!finished) journey.launches++
        break

      case "onboarding_complete":
        finished = true
        break

      case "register_success":
        firstAccountAt ??= at
        break

      case "step_view": {
        if (!stepId) break
        firstView ??= event
        if (!visit) {
          show(stepId, event)
          break
        }
        lastVisit = { stepId }
        const loggedType = text(event.stepType)
        if (loggedType) stepTypes.set(stepId, loggedType)
        // Shown again without having been left: the app was closed on it.
        closeVisit(stepId)
        openMs.set(stepId, 0)
        // The options tapped are counted visit by visit: coming back later to pick another one is no hesitation.
        picked.delete(stepId)
        visit.views++
        visit.exit = undefined
        if (event.via === "back") visit.returns = bump(visit.returns)
        // Shown again under another parcours (the choice was changed): the
        // screen now belongs to that one. A screen of the trunk stays there.
        const branch = text(event.branch)
        if (visit.branch !== undefined && branch !== undefined && branch !== visit.branch) {
          visit.branch = branch
          visit.index = finite(event.stepIndex) ?? visit.index
        }
        break
      }

      case "step_leave": {
        if (!stepId || !visit) break
        openMs.delete(stepId)
        visit.ms += durationMs ?? 0
        visit.exit = text(event.via) ?? UNKNOWN
        if (event.via === "back") visit.backs = bump(visit.backs)
        // A leave that carries an answer carries the current one: empty means
        // it was removed. Leaving with the back arrow validates nothing.
        if (typeof event.value === "string" && event.via !== "back") visit.answer = value
        if (lastVisit?.stepId === stepId) lastVisit.leftAfterMs = durationMs
        break
      }

      case "app_background": {
        if (!stepId || !visit) break
        const systemDialog = journey.platform === "android" && SYSTEM_DIALOG_STEP_TYPES.has(stepTypes.get(stepId) ?? "")
        if (!systemDialog) visit.backgrounds = bump(visit.backgrounds)
        // `durationMs` = time already spent on the screen during this visit.
        if (openMs.has(stepId)) openMs.set(stepId, Math.max(openMs.get(stepId) ?? 0, durationMs ?? 0))
        break
      }

      case "option_select":
        if (stepId && visit && value) {
          const options = picked.get(stepId) ?? new Set<string>()
          picked.set(stepId, options.add(value))
          visit.picks = Math.max(visit.picks ?? 0, options.size)
        }
        break

      case "option_toggle":
        if (visit && event.selected === false) visit.unticks = bump(visit.unticks)
        break

      case "option_max_reached":
        if (visit && value) (visit.maxReached ??= {})[value] = bump(visit.maxReached[value])
        break

      case "cta_disabled_tap":
        if (visit) visit.disabledTaps = bump(visit.disabledTaps)
        break

      case "language_change":
        journey.languageChanges = bump(journey.languageChanges)
        break

      case "consent_accept_all":
        ;(journey.consent ??= { acceptedAll: false }).acceptedAll = true
        break

      case "consent_link_open":
        if (value) {
          const consent = (journey.consent ??= { acceptedAll: false })
          consent.links = push(consent.links, value)
        }
        break

      case "consent_next_blocked": {
        const consent = (journey.consent ??= { acceptedAll: false })
        consent.blocked = bump(consent.blocked)
        break
      }

      case "permission_result": {
        const kind = stepId ? PERMISSION_KIND_BY_STEP_TYPE[stepTypes.get(stepId) ?? ""] : undefined
        if (kind && value) {
          // Asked again after a return: the last answer is the one that counts.
          journey.permissions = [...(journey.permissions ?? []).filter((p) => p.kind !== kind), { kind, result: value }]
        }
        break
      }

      case "program_goal_toggle":
        if (value && typeof event.selected === "boolean") programGoals.set(value, event.selected)
        break

      case "program_why_open":
        if (value) {
          const program = (journey.program ??= {})
          program.whyOpened = pushOnce(program.whyOpened, value)
        }
        break

      case "program_source_open":
        if (value) {
          const program = (journey.program ??= {})
          program.sourcesOpened = pushOnce(program.sourcesOpened, value)
        }
        break

      case "hold_start":
        journey.hold ??= { cancels: 0, cancelMs: [], completed: false }
        break

      case "hold_cancel": {
        const hold = (journey.hold ??= { cancels: 0, cancelMs: [], completed: false })
        // Once the long press has completed, the app still logs the finger
        // lifting (or a stray tap) as a cancel: nothing was released too early.
        if (hold.completed) break
        hold.cancels++
        if (durationMs !== undefined) hold.cancelMs.push(durationMs)
        break
      }

      case "hold_complete":
        ;(journey.hold ??= { cancels: 0, cancelMs: [], completed: false }).completed = true
        break

      case "register_method":
        if (value) (journey.register ??= { attempts: [] }).attempts.push(value)
        break

      case "register_cancel": {
        const register = (journey.register ??= { attempts: [] })
        register.cancels = bump(register.cancels)
        lastCancel = at !== undefined ? { method: value, at } : undefined
        break
      }

      case "register_error": {
        const register = (journey.register ??= { attempts: [] })
        const code = text(event.detail) ?? UNKNOWN
        if (code === EMAIL_TYPO_PROMPT) {
          register.typoPrompts = bump(register.typoPrompts)
          break
        }
        register.errors = push(register.errors, `${value ?? UNKNOWN}:${code}`)
        // A sign-in that fails leaves no session, which the app first logs as
        // a dismissed sheet, then, a few milliseconds later, as this error:
        // that sheet was not dismissed.
        if (lastCancel && lastCancel.method === value && at !== undefined && at - lastCancel.at < SAME_ATTEMPT_MS) {
          const dismissed = (register.cancels ?? 1) - 1
          register.cancels = dismissed > 0 ? dismissed : undefined
          lastCancel = undefined
        }
        break
      }

      case "register_login_tap": {
        const register = (journey.register ??= { attempts: [] })
        register.loginTaps = bump(register.loginTaps)
        break
      }

      case "paywall_result":
        // Final results are on the session record (paywallResult).
        if (value === "not_presented" || value === "error") {
          journey.paywallMisses = push(journey.paywallMisses, value)
        }
        break
    }
  }

  // The last screen shown is where the journey stands. Its last visit lasted
  // what its leave says, or what the last trip to the background says when it
  // was never left; zero means not logged.
  if (lastVisit) {
    journey.lastStepId = lastVisit.stepId
    const lastVisitMs = openMs.get(lastVisit.stepId) ?? lastVisit.leftAfterMs
    if (lastVisitMs) journey.lastVisitMs = lastVisitMs
  }
  for (const stepId of [...openMs.keys()]) closeVisit(stepId)

  // The record's `registeredAt` is rewritten by every sign-in that follows: the account dates from the first one.
  if (journey.registeredAt !== undefined && firstAccountAt !== undefined && firstAccountAt < journey.registeredAt) {
    journey.registeredAt = firstAccountAt
  }

  journey.steps = [...steps.values()]
  const stepOfType = (type: string) => journey.steps.find((step) => stepTypes.get(step.id) === type)

  const choices = parseConsentChoices(stepOfType("consent")?.answer)
  if (choices) (journey.consent ??= { acceptedAll: false }).choices = choices

  // The programme screen forgets its unticked boxes when it is shown again:
  // only the goals missing from the programme kept were really removed.
  const kept = new Set(stepOfType("program")?.answer?.split(","))
  const removed = [...programGoals].flatMap(([goal, selected]) => (selected || kept.has(goal) ? [] : goal))
  if (removed.length > 0) (journey.program ??= {}).removed = removed

  journey.coverage = coverageOf(journey.steps, firstView)
  return journey
}

function coverageOf(steps: StepVisit[], firstView: OnboardingEventDoc | undefined): JourneyCoverage {
  if (steps.length > 0 && steps.every((step) => step.id === REGISTER_STEP_ID)) return "register"
  return firstView && finite(firstView.stepIndex) === 0 ? "full" : "partial"
}

function byTimeThenSeq(a: OnboardingEventDoc, b: OnboardingEventDoc): number {
  return (finite(a.t) ?? 0) - (finite(b.t) ?? 0) || (finite(a.seq) ?? 0) - (finite(b.seq) ?? 0)
}

/**
 * Builds the dataset batch after batch, so that the raw events of a long
 * period are never all in memory: `add` takes some sessions with ALL their
 * events, `build` returns the journeys, most recent first.
 */
export function onboardingDatasetBuilder(range: { from: string; to: string }) {
  const journeys: Journey[] = []
  const screens: Record<string, ScreenInfo> = {}
  const seeScreen = (stepId: string, loggedType: string | undefined) => {
    screens[stepId] ??= screenInfo(stepId, loggedType)
  }

  return {
    add(sessions: OnboardingSessionDoc[], events: OnboardingEventDoc[]): void {
      const eventsBySession = new Map<string, OnboardingEventDoc[]>()
      for (const event of events) {
        const sessionId = text(event.sessionId)
        if (!sessionId) continue
        const list = eventsBySession.get(sessionId)
        if (list) list.push(event)
        else eventsBySession.set(sessionId, [event])
      }
      for (const session of sessions) {
        journeys.push(buildJourney(session, (eventsBySession.get(session.id) ?? []).sort(byTimeThenSeq), seeScreen))
      }
    },

    build(): OnboardingDataset {
      return {
        from: range.from,
        to: range.to,
        generatedAt: new Date().toISOString(),
        journeys: journeys.sort((a, b) => b.startedAt - a.startedAt),
        screens,
        goals: GOAL_TITLES,
      }
    },
  }
}
